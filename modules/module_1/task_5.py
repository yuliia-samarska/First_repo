# Обчислення гіпотенузи
side_a = 45
side_b = 78
hypotenuse = (side_a**2 + side_b**2)**0.5
print(f"Гіпотенуза трикутника зі сторонами {side_a} та {side_b} дорівнює {hypotenuse}")

# Обчислення площі трикутника
S = side_a * side_b / 2
print(f"Площа трикутника зі сторонами {side_a} та {side_b} дорівнює {S}")